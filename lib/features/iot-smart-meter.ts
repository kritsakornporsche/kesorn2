export function computeInstantElectricalMetrics(
  relayState: RelayState,
  appliances: SmartMeterRoomNode['appliances'],
  profile: TenantLoadProfile
): {
  voltage: number;
  current: number;
  activePowerWatt: number;
  powerFactor: number;
  frequencyHz: number;
} {
  const baseVoltage = 228.5 + (Math.random() * 3.2 - 1.6);
  const frequencyHz = Number((49.95 + Math.random() * 0.1).toFixed(2));

  if (relayState === 'OFF') {
    return {
      voltage: Number(baseVoltage.toFixed(1)),
      current: 0,
      activePowerWatt: 0,
      powerFactor: 1.0,
      frequencyHz,
    };
  }

  // Standby load (refrigerator + router + lighting)
  let loadWatt = profile === 'VACANT' ? 18 + Math.random() * 8 : 85 + Math.random() * 35;

  if (appliances.acOn) {
    loadWatt += 1050 + Math.random() * 220;
  }
  if (appliances.waterHeaterOn) {
    loadWatt += 3200 + Math.random() * 300;
  }
  if (appliances.pcLoadOn) {
    loadWatt += 380 + Math.random() * 90;
  }
  if (appliances.faultOverload) {
    loadWatt += 4500 + Math.random() * 600;
  }

  const pf = Number((appliances.acOn || appliances.faultOverload ? 0.91 + Math.random() * 0.05 : 0.96 + Math.random() * 0.03).toFixed(2));
  // Voltage sag under heavy load
  const voltage = Number((baseVoltage - (loadWatt / 1000) * 1.15).toFixed(1));
  const current = Number((loadWatt / (voltage * pf)).toFixed(2));

  return {
    voltage,
    current,
    activePowerWatt: Math.round(loadWatt),
    powerFactor: pf,
    frequencyHz,
  };
}

export function executeAutoBillingCalculation(
  rooms: SmartMeterRoomNode[],
  billingCycle: string
): AutoBillingPipelineResult {
  const occupiedRooms = rooms.filter((r) => r.occupancyStatus === 'OCCUPIED');
  const bills: AutoGeneratedBillItem[] = [];
  const highUsageRooms: string[] = [];

  let totalElectricUnitsKwh = 0;
  let totalElectricRevenue = 0;
  let totalWaterRevenue = 0;
  let totalRentRevenue = 0;
  let grandTotalRevenue = 0;

  const dueDate = `${billingCycle}-05`;
  const generatedAt = new Date().toISOString();

  for (const room of occupiedRooms) {
    const electricUnits = Math.max(0, Number((room.currentMeterKwh - room.previousMonthKwh).toFixed(2)));
    const electricAmount = Number((electricUnits * ELECTRIC_RATE_THB).toFixed(2));
    const waterUnits = Math.max(1, room.waterUnitsUsed || 1);
    const waterAmount = WATER_FLAT_RATE_THB;
    const roomRent = room.rentPrice;
    const commonFee = COMMON_FEE_THB;
    const totalAmount = Number((roomRent + electricAmount + waterAmount + commonFee).toFixed(2));

    if (electricUnits >= 250) {
      highUsageRooms.push(room.roomNumber);
    }

    const promptPayPayload = generatePayload(DORM_PROMPTPAY_NUMBER, { amount: totalAmount });
    const billRef = `INV-${billingCycle.replace('-', '')}-${room.roomNumber}`;

    const canonicalPayload = `${billRef}|${room.roomNumber}|${room.tenantName}|${electricUnits}|${totalAmount}|${generatedAt}`;
    const sha256ReceiptHash = crypto.createHash('sha256').update(canonicalPayload).digest('hex').toUpperCase();

    totalElectricUnitsKwh += electricUnits;
    totalElectricRevenue += electricAmount;
    totalWaterRevenue += waterAmount;
    totalRentRevenue += roomRent + commonFee;
    grandTotalRevenue += totalAmount;

    bills.push({
      billRef,
      roomNumber: room.roomNumber,
      floor: room.floor,
      tenantName: room.tenantName || `ผู้เช่าห้อง ${room.roomNumber}`,
      nodeMode: room.nodeMode,
      billingCycle,
      dueDate,
      previousKwh: room.previousMonthKwh,
      currentKwh: room.currentMeterKwh,
      electricUnits,
      electricRate: ELECTRIC_RATE_THB,
      electricAmount,
      waterPreviousM3: room.waterPreviousM3,
      waterCurrentM3: room.waterCurrentM3,
      waterUnits,
      waterAmount,
      roomRent,
      commonFee,
      totalAmount,
      promptPayTarget: DORM_PROMPTPAY_NUMBER,
      promptPayPayload,
      sha256ReceiptHash,
      anomalyWarning:
        electricUnits >= 250
          ? `หน่วยไฟสูงเกินเกณฑ์ (${electricUnits} kWh) แนะนำตรวจสอบแอร์หรือเครื่องใช้ไฟฟ้า`
          : null,
      generatedAt,
    });
  }

  return {
    pipelineRunId: `PIPE-${Date.now()}`,
    executedAt: generatedAt,
    billingCycle,
    totalRoomsScanned: rooms.length,
    totalBillsGenerated: bills.length,
    totalElectricUnitsKwh: Number(totalElectricUnitsKwh.toFixed(2)),
    totalElectricRevenue: Number(totalElectricRevenue.toFixed(2)),
    totalWaterRevenue: Number(totalWaterRevenue.toFixed(2)),
    totalRentRevenue: Number(totalRentRevenue.toFixed(2)),
    grandTotalRevenue: Number(grandTotalRevenue.toFixed(2)),
    highUsageRooms,
    syncedToDbCount: 0,
    bills,
  };
}

