export interface SmartMeterRoomNode {
  roomNumber: string;
  floor: 1 | 2;
  roomType: 'ห้องแอร์ (VIP)' | 'ห้องแอร์' | 'ห้องพัดลม';
  occupancyStatus: 'OCCUPIED' | 'AVAILABLE' | 'MAINTENANCE';
  tenantName: string | null;
  rentPrice: number;
  nodeMode: NodeMode;
  deviceId: string;
  loadProfile: TenantLoadProfile;
  // Electrical telemetry (PZEM-004T parameters)
  voltage: number;          // Volts (V)
  current: number;          // Amperes (A)
  activePowerWatt: number;  // Watts (W)
  powerFactor: number;      // 0.00 - 1.00
  frequencyHz: number;      // Hz (e.g., 50.0)
  previousMonthKwh: number; // เลขมิเตอร์ต้นเดือน
  currentMeterKwh: number;  // เลขมิเตอร์ปัจจุบันสะสม
  monthlyUnitsKwh: number;  // หน่วยไฟที่ใช้ในเดือนนี้
  // Water meter telemetry
  waterPreviousM3: number;
  waterCurrentM3: number;
  waterUnitsUsed: number;
  // Relay & Appliance load states
  relayState: RelayState;
  appliances: {
    acOn: boolean;
    waterHeaterOn: boolean;
    pcLoadOn: boolean;
    faultOverload: boolean;
  };
  // ESP32 Connectivity metadata
  esp32Meta: {
    macAddress: string;
    ipAddress: string;
    wifiRssi: number;
    firmwareVersion: string;
    samplingIntervalMs: number;
    isHardwareConnected: boolean;
    lastHardwarePacketAt: string | null;
    lastUpdatedAt: string;
    pendingCommand: Esp32CommandType | null;
    espStatus?: 'ONLINE' | 'OFFLINE';
    pzemStatus?: 'CONNECTED' | 'WAITING_AC' | 'DISCONNECTED' | 'SIMULATED';
    rawSensorStatus?: string;
  };
}

