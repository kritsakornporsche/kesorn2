export type RelayState = 'ON' | 'OFF';

export type Esp32CommandType =
  | 'RELAY_ON'
  | 'RELAY_OFF'
  | 'FORCE_READ_NOW'
  | 'RESET_KWH_COUNTER'
  | 'SET_INTERVAL_2S'
  | 'SET_INTERVAL_5S'
  | 'REBOOT_ESP32';

